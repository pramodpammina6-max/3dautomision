'use client';
import { useRouter } from 'next/navigation';
import { useState } from 'react';
import { ArrowRight, ImageUp, Loader2, Wand2 } from 'lucide-react';
import { Button } from '@/common/components/ui/button';
import { Card, CardDescription, CardTitle } from '@/common/components/ui/card';
import { Input, Label, Textarea } from '@/common/components/ui/input';
import { ROUTES } from '@/common/routes';
import type { FloorPlan } from '@/common/types';
import { projectService } from '@/features/dashboard';
import { PlanPreview } from '@/features/floorplan-editor';
import { floorplanAiService } from '../service/floorplanAiService';
import { floorplanAiStyles as s } from '../styles/floorplanAi.styles';

export function FloorplanImportContainer() {
  const router = useRouter();
  const [image, setImage] = useState<string | null>(null);
  const [prompt, setPrompt] = useState('');
  const [name, setName] = useState('My floor plan');
  const [result, setResult] = useState<{ plan: FloorPlan; source: 'openai' | 'demo' } | null>(null);
  const [status, setStatus] = useState<'idle' | 'generating' | 'saving'>('idle');
  const [error, setError] = useState<string | null>(null);

  async function onFile(file?: File) {
    if (!file) return;
    if (file.size > 8 * 1024 * 1024) return setError('Image must be under 8 MB');
    setError(null);
    setImage(await floorplanAiService.readFile(file));
  }

  async function generate() {
    setError(null);
    setStatus('generating');
    try {
      setResult(
        await floorplanAiService.generate({
          imageDataUrl: image ?? undefined,
          prompt: prompt || undefined,
        }),
      );
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setStatus('idle');
    }
  }

  async function open3d() {
    if (!result) return;
    setStatus('saving');
    try {
      const project = await projectService.create(name, { ...result.plan, name });
      router.push(`${ROUTES.project(project.id)}?tab=3d`);
    } catch (e) {
      setError((e as Error).message);
      setStatus('idle');
    }
  }

  return (
    <div className={s.page}>
      <Card className="space-y-5">
        <div>
          <CardTitle>2D floor plan → 3D model</CardTitle>
          <CardDescription>
            Upload a floor plan (PNG/JPG/WebP) or describe one. The AI returns structured floor plan JSON that becomes
            an editable 3D model.
          </CardDescription>
        </div>
        <label className={s.dropzone}>
          {image ? (
            // eslint-disable-next-line @next/next/no-img-element
            <img src={image} alt="Uploaded floor plan" className="max-h-56 rounded-md object-contain" />
          ) : (
            <>
              <ImageUp className="size-8" />
              <span>Click to upload or drop a floor plan image</span>
            </>
          )}
          <input type="file" accept="image/png,image/jpeg,image/webp" className="hidden" onChange={(e) => onFile(e.target.files?.[0])} />
        </label>
        <div className="space-y-1.5">
          <Label htmlFor="prompt">Description / notes (optional)</Label>
          <Textarea
            id="prompt"
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            placeholder="e.g. 3 bedroom apartment, 12m × 9m, open kitchen, two bathrooms, balcony on the south side"
          />
        </div>
        {error && <p className="rounded-lg bg-rose-950/60 p-3 text-sm text-rose-300">{error}</p>}
        <Button className="w-full" onClick={generate} disabled={status !== 'idle' || (!image && !prompt.trim())}>
          {status === 'generating' ? <Loader2 className="animate-spin" /> : <Wand2 />}
          {status === 'generating' ? 'Analysing floor plan…' : 'Generate floor plan JSON'}
        </Button>
      </Card>

      <div className={s.preview}>
        <div className="flex items-center justify-between border-b border-slate-800 px-4 py-3">
          <span className="text-sm font-medium text-slate-300">Preview</span>
          {result && (
            <span
              className={`${s.badge} ${result.source === 'openai' ? 'bg-emerald-500/15 text-emerald-300' : 'bg-amber-500/15 text-amber-300'}`}
            >
              {result.source === 'openai' ? 'Generated by OpenAI' : 'Demo mode (no OPENAI_API_KEY)'}
            </span>
          )}
        </div>
        <div className="flex-1">
          {result ? (
            <PlanPreview plan={result.plan} />
          ) : (
            <div className="grid h-full place-items-center p-10 text-sm text-slate-500">
              The detected walls, rooms, doors and windows appear here.
            </div>
          )}
        </div>
        {result && (
          <div className="flex flex-wrap items-center gap-3 border-t border-slate-800 p-4">
            <span className="text-sm text-slate-400">
              {result.plan.rooms.length} rooms · {result.plan.walls.length} walls · {result.plan.openings.length} openings
            </span>
            <Input className="ml-auto w-56" value={name} onChange={(e) => setName(e.target.value)} />
            <Button onClick={open3d} disabled={status !== 'idle'}>
              {status === 'saving' ? <Loader2 className="animate-spin" /> : <ArrowRight />} Create 3D model
            </Button>
          </div>
        )}
      </div>
    </div>
  );
}
